"""Generate site/config.js from environment variables (build/deploy step).

    OPENROUTER_API_KEY   the live key to inject (empty -> whispers mode)
    SEANCE_BASE_URL      optional, default OpenRouter
    SEANCE_MODEL         optional, default google/gemma-3-27b-it:free

USAGE
    python scripts/build_site.py        # run before serving locally; the
                                        # Pages workflow runs it at deploy

!! READ THIS BEFORE INJECTING A KEY !!

site/config.js is served to every visitor — the key inside it is PUBLIC.
Anyone can open devtools and copy it. Only ever inject a throwaway key:
create a dedicated OpenRouter key restricted to free models with a $0 spend
limit (https://openrouter.ai/keys), or keep the site in whispers mode. The
ghost's built-in 1-in-5 throttle and 429 cooldown keep usage modest, but
they are politeness, not protection.
"""

from __future__ import annotations

import json
import os
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "site" / "config.js"

DEFAULT_BASE_URL = "https://openrouter.ai/api/v1"
DEFAULT_MODEL = "google/gemma-3-27b-it:free"


def main() -> None:
    key = os.environ.get("OPENROUTER_API_KEY", "").strip()
    base = os.environ.get("SEANCE_BASE_URL", "").strip() or DEFAULT_BASE_URL
    model = os.environ.get("SEANCE_MODEL", "").strip() or DEFAULT_MODEL

    js = (
        "// generated by scripts/build_site.py — do not edit by hand, do not commit\n"
        "// (gitignored). If a key is present it is PUBLIC once this page is served.\n"
        "window.SEANCE_WEB_CFG = {\n"
        f"  base_url: {json.dumps(base)},\n"
        f"  model: {json.dumps(model)},\n"
        f"  api_key: {json.dumps(key)},\n"
        "};\n"
    )
    OUT.write_text(js, encoding="utf-8")

    if key:
        print(f"site/config.js written — LIVE key injected (hidden), model: {model}")
    else:
        print("site/config.js written — no key: the site runs in whispers mode")


if __name__ == "__main__":
    main()
